// Generates src/lib/icons.generated.ts: static SVG inner markup for the
// Lucide icons the client uses (ISC license, see node_modules/lucide-solid).
import { readFileSync, writeFileSync } from "node:fs";

const names = process.argv.slice(2);
const out: Record<string, string> = {};
for (const name of names) {
  const src = readFileSync(`node_modules/lucide-solid/dist/source/icons/${name}.jsx`, "utf8");
  const start = src.indexOf("var __iconData = ") + "var __iconData = ".length;
  const data = Function(`return ${src.slice(start, src.indexOf("\n};", start) + 2)}`)() as { node: [string, Record<string, string>][] };
  const parsed = data.node;
  out[name] = parsed
    .map(([tag, attrs]) => `<${tag} ${Object.entries(attrs).filter(([k]) => k !== "key").map(([k, v]) => `${k}="${v}"`).join(" ")}/>`)
    .join("");
}
writeFileSync(
  "src/lib/icons.generated.ts",
  `// Generated by scripts/gen-icons.ts from lucide-solid 1.55.0 (ISC). Do not edit.\nexport const ICONS: Record<string, string> = ${JSON.stringify(out, null, 1)};\n`,
);
console.log(`wrote ${names.length} icons`);
